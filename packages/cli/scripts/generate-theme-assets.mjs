// @oktis-works/cli - Generates `src/generated/theme-assets.ts` from the real
// theme directory.
//
// `themes/default/` in this monorepo is the ONLY source of truth for the
// default theme: it is what the repository ships, what the web app renders
// and what a published package carries in `dist/themes/default`. The CLI
// cannot read that directory at runtime (it publishes only `dist/`), so the
// files are embedded as strings — this script performs that embedding.
//
// Why generate instead of maintaining the strings by hand: the hand-written
// copy drifted silently (missing `page-home.astro`, `page-blog.astro` and
// `src/theme.css`, stale `theme.json` and `dist/theme.css`), so `okcms init`
// scaffolded a theme that did not exist in the monorepo. `theme-assets.test.ts`
// compares this generated file against the directory and fails on any drift.
//
// Runs as part of `bun run build` / `prepack` (before tsc). The generated file
// is committed, so a fresh checkout type-checks and tests without a prior build.

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = join(pkgRoot, '..', '..');
const THEME_SRC = join(repoRoot, 'themes', 'default');
const OUT_FILE = join(pkgRoot, 'src', 'generated', 'theme-assets.ts');

/** Files written as raw bytes; everything else is read/written as UTF-8 text. */
const BINARY_EXTENSIONS = new Set(['png', 'jpg', 'jpeg', 'gif', 'ico', 'svg', 'webp', 'avif']);

/**
 * Emits the content as a template literal. Backslashes, backticks and `${`
 * are escaped so the string evaluates back to the exact bytes on disk.
 */
function toTemplateLiteral(content) {
  const escaped = content
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
  return `\`${escaped}\``;
}

function collect(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...collect(full));
    else out.push(full);
  }
  return out;
}

function main() {
  const absolute = collect(THEME_SRC)
    .map((path) => ({ path, relative: relative(THEME_SRC, path).split('\\').join('/') }))
    .sort((a, b) => (a.relative < b.relative ? -1 : a.relative > b.relative ? 1 : 0));

  const text = [];
  const binary = [];

  for (const file of absolute) {
    const ext = file.relative.split('.').pop()?.toLowerCase() ?? '';
    if (BINARY_EXTENSIONS.has(ext)) {
      binary.push([file.relative, readFileSync(file.path).toString('base64')]);
    } else {
      text.push([file.relative, readFileSync(file.path, 'utf-8')]);
    }
  }

  if (!text.some(([name]) => name === 'theme.json')) {
    console.error(`✗ ${THEME_SRC} has no theme.json — not a theme directory`);
    process.exit(1);
  }

  const lines = [
    '// GENERATED by scripts/generate-theme-assets.mjs — do not edit by hand.',
    '//',
    '// Source of truth: themes/default/ in this monorepo (the theme the web app',
    '// actually renders and the published package carries in dist/themes/default).',
    '// Regenerated by `bun run build`; `src/theme-assets.test.ts` fails when this',
    '// file drifts from the directory it mirrors.',
    '',
    '/** Complete default theme written by `okcms init` (paths relative to themes/default/). */',
    'export const DEFAULT_THEME_FILES: Record<string, string> = {',
  ];

  for (const [name, content] of text) {
    lines.push(`  ${JSON.stringify(name)}: ${toTemplateLiteral(content)},`);
  }
  lines.push('};', '');
  lines.push(
    '/**',
    ' * Binary files of the default theme: base64 so the source stays valid TS,',
    ' * decoded into a Buffer on write (a string would corrupt the PNG).',
    ' */',
    'export const DEFAULT_THEME_BINARY_FILES: Record<string, string> = {'
  );
  for (const [name, base64] of binary) {
    lines.push(`  ${JSON.stringify(name)}: '${base64}',`);
  }
  lines.push('};', '');
  lines.push(
    "/** Manifest of the default theme (`theme.json`, the canonical theme name). */",
    "export const DEFAULT_THEME_MANIFEST: string = DEFAULT_THEME_FILES['theme.json'] ?? '';",
    '',
    '/** Default theme stylesheet, served straight from `dist/theme.css` (no build). */',
    "export const DEFAULT_THEME_CSS: string = DEFAULT_THEME_FILES['dist/theme.css'] ?? '';",
    '',
    '/** `.astro` hierarchy templates of the default theme, at the theme root. */',
    'export const THEME_TEMPLATE_FILES: Record<string, string> = Object.fromEntries(',
    "  Object.entries(DEFAULT_THEME_FILES).filter(([file]) => file.endsWith('.astro'))",
    ');',
    ''
  );

  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, lines.join('\n'), 'utf-8');
  console.log(
    `✓ theme-assets generated (${text.length} text + ${binary.length} binary from themes/default)`
  );
}

main();
